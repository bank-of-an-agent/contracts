#!/usr/bin/env bash
# Derive everything that follows deterministically from the proving key and the compiled
# circuit: the verification key, the Solidity verifier, the witness WASM and the manifest.
set -euo pipefail
cd "$(dirname "$0")/.."
S=./node_modules/.bin/snarkjs
$S zkey export verificationkey artifacts/agent_claims.zkey artifacts/verification_key.json >/dev/null
mkdir -p ../src/verifiers
$S zkey export solidityverifier artifacts/agent_claims.zkey build/Groth16Verifier.sol >/dev/null
sed -e 's/^pragma solidity .*;/pragma solidity 0.8.30;/' \
    -e 's/^contract Groth16Verifier {/\/\/\/ @title AgentClaimsGroth16Verifier\n\/\/\/ @notice Generated by snarkjs 0.7.6 from circuits\/artifacts\/agent_claims.zkey (scripts\/export.sh). Do not edit.\ncontract AgentClaimsGroth16Verifier {/' \
    build/Groth16Verifier.sol >../src/verifiers/AgentClaimsGroth16Verifier.sol
cp build/agent_claims_js/agent_claims.wasm artifacts/agent_claims.wasm
node scripts/manifest.mjs
